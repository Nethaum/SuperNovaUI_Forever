"""
Writes SuperNovaUI_Forever/Data/Recipes.lua from the data files of the addon VoidProf (bughatti / Vede, MIT).

    python tools/gen-recipes.py "<path to VoidProf folder>"

Kept, for every profession (cap `max`) and recipe: spell id, English name, the skill needed to learn it (`min`), when it turns
yellow and grey, how many points a craft gives (`ups`), the reagents (`mats`: count, then the item ids that can fill the slot),
and, for a recipe that is learned from an item, the item's id (`book`; true when it is not known). Plus `items`: the English name of every reagent
and recipe item. (VoidProf's table also has a buy price, but that is only the item's own price: it does not say that any
vendor sells it, so it is left out.) The notice of VoidProf is written at the top of the generated file
(the MIT licence asks for it). Needs `pip install lupa`.
"""
import sys
from pathlib import Path

from lupa.lua51 import LuaRuntime

OUT = Path(__file__).resolve().parent.parent / "SuperNovaUI_Forever" / "Data" / "Recipes.lua"


def lua_string(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    folder = Path(sys.argv[1])
    lua = LuaRuntime(unpack_returned_tuples=True)
    lua.execute("GetBuildInfo = function() return '1', '1', 'x', 16001 end")
    lua.execute((folder / "ForeverProfessionData.lua").read_text(encoding="utf-8"))
    data = lua.eval("VoidProf.ProfessionData")
    build = str(data["build"])

    # recipe items: ForeverRecipes.lua rows are { profession, "name", crafted item, learn skill, recipe item, category, ... }
    book_by_item, book_by_name = {}, {}
    path = (folder / "ForeverRecipes.lua").as_posix()
    rows = lua.eval(f'(function() local ns = {{}}; loadfile("{path}")("VoidProf", ns); return ns.ForeverRecipes end)()')
    for row in rows.values():
        crafted, recipe_item = int(row[3]), int(row[5])
        if recipe_item:
            if crafted:
                book_by_item[crafted] = recipe_item
            book_by_name[str(row[2])] = recipe_item

    items = data["items"]
    wanted = set()
    lines = [
        "-- Generated by tools/gen-recipes.py from the Forever recipe data of VoidProf (https://github.com/bughatti/voidprof,",
        f"-- build {build}). Do not edit by hand. VoidProf is MIT licensed, Copyright (c) 2026 Vede: see THIRD_PARTY_NOTICES.md.",
        "-- SN.RecipeData.professions = { { id, name, max = highest skill, recipes = { { spellId, \"English name\", min = skill to learn,",
        "--   yellow, grey, ups = points per craft, book = recipe item id (or true), mats = { { count, itemId, itemId... }, ... } }, ... } }, ... }",
        "-- SN.RecipeData.items[itemId] = \"English name\" (reagents and recipe items)",
        "local addonName, SN = ...",
        "",
        "SN.RecipeData = {",
        f'    build = "{build}",',
        "    professions = {",
    ]
    total = 0

    for profession in data["professions"].values():
        lines.append(f'        {{ id = "{profession["id"]}", name = "{profession["name"]}", max = {int(profession["max"])}, recipes = {{')

        for recipe in profession["recipes"].values():
            minimum = recipe["min"]

            if minimum is None:
                continue

            fields = [f"{int(recipe[1])}", lua_string(recipe[2]), f"min = {int(minimum)}"]
            for key in ("yellow", "grey", "ups"):
                if recipe[key] is not None:
                    fields.append(f"{key} = {int(recipe[key])}")

            if recipe["book"]:
                makes = recipe["makes"]
                made = int(makes["ids"][1]) if makes and makes["ids"] else 0
                book = book_by_item.get(made) or book_by_name.get(str(recipe[2]))
                fields.append(f"book = {book}" if book else "book = true")
                if book:
                    wanted.add(book)

            mats = []
            for mat in (recipe["mats"] or {}).values():
                ids = [int(i) for i in mat["ids"].values()]
                wanted.update(ids)
                mats.append("{ " + ", ".join([str(int(mat["n"]))] + [str(i) for i in ids]) + " }")
            if mats:
                fields.append("mats = { " + ", ".join(mats) + " }")

            lines.append("            { " + ", ".join(fields) + " },")
            total += 1

        lines.append("        } },")

    lines += ["    },", "    items = {"]
    for item_id in sorted(wanted):
        entry = items[item_id]
        if entry is not None:
            lines.append(f"        [{item_id}] = {lua_string(entry[1])},")
    lines += ["    },", "}", ""]

    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{total} recipes written to {OUT.name} ({OUT.stat().st_size} bytes), build {build}, {len(wanted)} items")


if __name__ == "__main__":
    main()
